from pathlib import Path
root=Path(__file__).resolve().parent
chunks=['-- Auto Candy v1.1.1 | generated by build.py; edit source modules instead.\n']
for name in ['Core','Actions','Gui','ServerHop','Main']:
    filename='main.lua' if name=='Main' else name+'.lua'
    chunks.append('local '+name+' = (function()\n'+(root/filename).read_text()+'\nend)()\n')
chunks.append('return Main.start(Core, Actions, Gui, ServerHop)\n')
(root/'auto_candy.lua').write_text('\n'.join(chunks))
print('Built auto_candy.lua')
